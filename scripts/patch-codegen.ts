// npx tsx ./scripts/patch-codegen.ts
//
// Post-processes Sentio CLI codegen output to work around an issue where
// sentio gen sometimes emits hex-address import paths (e.g.
//   import * as _0x113a1769... from "./0x113a1769....js"
// ) for dependencies that are actually generated under a friendly name in the
// same directory (e.g. multi_rewards.ts). The hex-named .ts file doesn't
// exist, so the TypeScript compiler fails.
//
// Strategy: for each src/types/aptos/<chain>/ directory, build a map of
// declared address -> friendly filename by reading each .ts file's
// DEFAULT_OPTIONS.address. Then, for each address that has a friendly file
// but is also referenced via hex-named imports, write a tiny stub
//   src/types/aptos/<chain>/0x<hex>.ts
// that re-exports everything from the friendly module. This satisfies the
// import without touching the auto-generated files (which would be clobbered
// on the next gen run).

import fs from "fs/promises";
import path from "path";

const TYPES_ROOT = path.join(process.cwd(), "src", "types", "aptos");

async function listSubdirs(dir: string): Promise<string[]> {
  try {
    const entries = await fs.readdir(dir, { withFileTypes: true });
    return entries.filter((e) => e.isDirectory()).map((e) => path.join(dir, e.name));
  } catch {
    return [];
  }
}

// Pull the address out of `DEFAULT_OPTIONS = { address: "0x...", ... }`.
// We try both single- and multi-line forms since prettier may have reflowed it.
function extractDefaultAddress(content: string): string | null {
  const re = /DEFAULT_OPTIONS[^{]*\{[\s\S]*?address:\s*"(0x[0-9a-fA-F]+)"/;
  const m = re.exec(content);
  if (!m) return null;
  // Normalize: drop leading zeros after 0x to compare against various forms.
  return m[1].toLowerCase();
}

// Build map: lowercase-normalized 0x address -> friendly stem (no .ts).
async function buildAddressMap(chainDir: string): Promise<Map<string, string>> {
  const map = new Map<string, string>();
  const files = await fs.readdir(chainDir);
  for (const f of files) {
    if (!f.endsWith(".ts")) continue;
    if (f === "index.ts") continue;
    const stem = f.replace(/\.ts$/, "");
    // Skip hex-named files — those are dependency stubs without a friendly alias.
    if (/^0x[0-9a-f]+$/i.test(stem)) continue;
    const content = await fs.readFile(path.join(chainDir, f), "utf-8");
    const addr = extractDefaultAddress(content);
    if (addr) map.set(normalizeHex(addr), stem);
  }
  return map;
}

function normalizeHex(addr: string): string {
  // Strip 0x, drop leading zeros, lowercase. Aptos addresses are 32 bytes,
  // but addresses appear in both fully-padded and stripped forms.
  return "0x" + addr.toLowerCase().replace(/^0x/, "").replace(/^0+/, "");
}

// Scan a chain dir's existing .ts files for any import that targets ./0x<hex>.js
// where the address exists in our friendly map. Returns the set of hex strings
// we need to create stubs for.
async function findMissingHexStubs(chainDir: string, friendly: Map<string, string>): Promise<Set<string>> {
  const needed = new Set<string>();
  const files = await fs.readdir(chainDir);
  const existingStems = new Set(files.filter((f) => f.endsWith(".ts")).map((f) => f.replace(/\.ts$/, "")));

  const importRe = /from\s+["']\.\/(0x[0-9a-fA-F]+)\.js["']/g;
  for (const f of files) {
    if (!f.endsWith(".ts")) continue;
    const content = await fs.readFile(path.join(chainDir, f), "utf-8");
    let m: RegExpExecArray | null;
    while ((m = importRe.exec(content)) !== null) {
      const hex = m[1];
      if (existingStems.has(hex)) continue; // already exists, fine
      if (friendly.has(normalizeHex(hex))) {
        needed.add(hex);
      }
    }
  }
  return needed;
}

async function writeStubs(chainDir: string, hexAddrs: Set<string>, friendly: Map<string, string>) {
  for (const hex of hexAddrs) {
    const friendlyStem = friendly.get(normalizeHex(hex));
    if (!friendlyStem) continue;
    const stubPath = path.join(chainDir, `${hex}.ts`);
    const stub =
      "// Auto-generated by scripts/patch-codegen.ts — do not edit.\n" +
      `// Re-exports ./${friendlyStem}.ts under its hex-address alias so that\n` +
      "// sibling modules whose codegen used the hex import form resolve correctly.\n\n" +
      `export * from "./${friendlyStem}.js";\n`;
    await fs.writeFile(stubPath, stub);
    console.log(`Wrote ${stubPath} → re-exports ./${friendlyStem}.js`);
  }
}

// Scan for `someNamespace.Foo` references where `someNamespace` is not imported
// but a sibling file `./someNamespace.ts` exists. This catches sentio gen's
// failure to import sibling modules from the same package (e.g.
// ichi_vault_meridian.ts referencing `timelocked.TimeLocked<bigint>` without
// importing ./timelocked.js).
async function injectMissingSiblingImports(chainDir: string) {
  const files = await fs.readdir(chainDir);
  const siblingStems = new Set(
    files.filter((f) => f.endsWith(".ts") && f !== "index.ts").map((f) => f.replace(/\.ts$/, "")),
  );

  for (const f of files) {
    if (!f.endsWith(".ts") || f === "index.ts") continue;
    const filePath = path.join(chainDir, f);
    const content = await fs.readFile(filePath, "utf-8");
    const selfStem = f.replace(/\.ts$/, "");

    // Find namespace identifiers used as `ident.X` in this file.
    // Conservative: only match alpha-snake identifiers, not hex addresses.
    const usedNamespaces = new Set<string>();
    const usageRe = /\b([a-z][a-z0-9_]*)\./g;
    let um: RegExpExecArray | null;
    while ((um = usageRe.exec(content)) !== null) {
      usedNamespaces.add(um[1]);
    }

    // Determine which of those are siblings that aren't already imported
    // AND aren't already locally declared as a namespace/class in this file
    // (sentio gen sometimes emits "fat" files that contain the full package's
    // namespaces inline — adding an import would shadow the local declaration).
    const toInject: string[] = [];
    for (const ns of usedNamespaces) {
      if (ns === selfStem) continue;
      if (!siblingStems.has(ns)) continue;
      const importRe = new RegExp(`from\\s+["']\\./${ns}\\.js["']`);
      if (importRe.test(content)) continue;
      const localDeclRe = new RegExp(`^export\\s+(?:class|namespace)\\s+${ns}\\b`, "m");
      if (localDeclRe.test(content)) continue;
      toInject.push(ns);
    }
    if (toInject.length === 0) continue;

    // Insert the missing imports just after the last existing top-level import.
    const lines = content.split("\n");
    let lastImportIdx = -1;
    for (let i = 0; i < lines.length; i++) {
      if (/^import\s/.test(lines[i])) lastImportIdx = i;
    }
    // Use a named import (not `import * as X`) so that when the sibling file
    // declares `export namespace X` we get the merged class+namespace bound to
    // `X` (not nested as `X.X`). Existing references like `X.TimeLocked` then
    // resolve correctly.
    const insertion = toInject.map((ns) => `import { ${ns} } from "./${ns}.js";`);
    const insertAt = lastImportIdx >= 0 ? lastImportIdx + 1 : 0;
    lines.splice(insertAt, 0, ...insertion);
    await fs.writeFile(filePath, lines.join("\n"));
    console.log(`Patched ${filePath}: injected imports for [${toInject.join(", ")}]`);
  }
}

async function patchChain(chainDir: string) {
  const friendly = await buildAddressMap(chainDir);
  const needed = await findMissingHexStubs(chainDir, friendly);
  await writeStubs(chainDir, needed, friendly);
  await injectMissingSiblingImports(chainDir);
}

async function main() {
  const chainDirs = await listSubdirs(TYPES_ROOT);
  for (const dir of chainDirs) {
    await patchChain(dir);
  }
}

main().catch((err) => {
  console.error("patch-codegen failed:", err);
  process.exit(1);
});
